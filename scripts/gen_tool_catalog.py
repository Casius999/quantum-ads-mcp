"""Generate the skill's tool catalog from the live connector registry.

The catalog an agent reads must match the tools the server actually registers, so it is generated
rather than hand-written, and tests/unit/test_tool_catalog_doc.py fails when the committed file
drifts from the registry.

Run:  uv run python scripts/gen_tool_catalog.py
"""

from __future__ import annotations

from pathlib import Path

from quantum_ads.core.versioning.version_manager import DEFAULT_API_VERSION
from quantum_ads.server import build_server

CATALOG_PATH = Path(__file__).resolve().parents[1] / "skill/quantum-ads/references/tool-catalog.md"

_ENV = {
    "GOOGLE_ADS_DEVELOPER_TOKEN": "x",
    "GOOGLE_ADS_CLIENT_ID": "x",
    "GOOGLE_ADS_CLIENT_SECRET": "x",
    "GOOGLE_ADS_REFRESH_TOKEN": "x",
}


def render_catalog() -> str:
    """Render every registered tool, grouped by connector and plane (read / write / meta)."""
    registry = build_server(env=_ENV, stream_factory=lambda creds, version: None).registry
    by_connector: dict[str, list[tuple[str, str, str]]] = {}
    for capability in registry.list_capabilities():
        for spec in capability.tools:
            plane = "read" if spec.read_only else "**write** (guarded)"
            by_connector.setdefault(capability.connector, []).append(
                (spec.name, plane, spec.summary)
            )
    total = sum(len(tools) for tools in by_connector.values())
    lines = [
        "# Quantum ADS — tool catalog",
        "",
        "<!-- GENERATED by scripts/gen_tool_catalog.py from the live connector registry."
        " Do not edit by hand; tests/unit/test_tool_catalog_doc.py enforces it. -->",
        "",
        f"**{total} tools across {len(by_connector)} groups** (Google Ads API "
        f"{DEFAULT_API_VERSION}). Every tool returns a structured dict; a missing backend yields "
        "`{error: BACKEND_NOT_CONFIGURED}` instead of raising. Write tools run "
        "a `validate_only` preview first (a failed validation never applies), then commit — in the "
        "same call with `QUANTUM_ADS_WRITE_MODE=auto`, or on a second call carrying the returned "
        "confirmation in `confirm` mode — and append a signed, hash-chained audit record. An "
        "optional policy file bounds what may be written. Writes are refused while "
        "`QUANTUM_ADS_READ_ONLY=true` (the default).",
        "",
    ]
    for connector in sorted(by_connector, key=lambda c: (c != "core", c)):
        lines += [f"## {connector}", "", "| Tool | Plane | Summary |", "|---|---|---|"]
        for name, plane, summary in sorted(by_connector[connector]):
            lines.append(f"| `{name}` | {plane} | {summary.replace('|', '/')} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    CATALOG_PATH.write_text(render_catalog(), encoding="utf-8")
    print(f"wrote {CATALOG_PATH}")


if __name__ == "__main__":
    main()
